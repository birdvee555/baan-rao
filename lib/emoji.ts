/**
 * กำหนด Icon อัตโนมัติ:
 * 1. ตรวจสอบชื่อสินค้ากับ AUTO_ICON_RULES
 * 2. ถ้าไม่พบ ใช้ Icon ตามหมวดหมู่ (ผัก 🥬, ของสด 🥩, ผลไม้ 🍎, อื่นๆ 📦)
 * 3. Default fallback เป็น 📦
 */
export function determineProductIcon(name: string, categoryNameOrIcon?: string | null): string {
  const n = (name || "").trim();
  if (n) {
    for (const [key, icon] of AUTO_ICON_RULES) {
      if (n.includes(key)) return icon;
    }
  }

  // Fallback ตามหมวดหมู่
  if (categoryNameOrIcon) {
    const cat = categoryNameOrIcon.trim();
    if (cat.includes("ผัก") || cat.includes("🥬")) return "🥬";
    if (cat.includes("ของสด") || cat.includes("เนื้อ") || cat.includes("🥩")) return "🥩";
    if (cat.includes("ผลไม้") || cat.includes("🍎")) return "🍎";
    if (cat.includes("อื่นๆ") || cat.includes("📦")) return "📦";
  }

  return "📦";
}

/** สำหรับ backward compatibility */
export function suggestEmoji(name: string): string {
  return determineProductIcon(name);
}

