export const UNITS = [
  "ตัว", "ชิ้น", "อัน", "ถุง", "กก.", "ขีด", "หัว", "กำ", "ต้น",
  "ลูก", "แผง", "กล่อง", "ขวด", "แพ็ค", "หวี",
];

/** ของที่ชั่งเป็นน้ำหนักปรับทีละครึ่ง ที่เหลือปรับทีละ 1 */
export function stepFor(unit: string): number {
  return unit === "กก." || unit === "ขีด" ? 0.5 : 1;
}
